// Turns every svg/*.svg into a React component in src/icons/, plus an index.
//
//   svg/chevron-down.svg  →  src/icons/ChevronDownIcon.tsx  →  <ChevronDownIcon />
//
// The SVG files only hold the shapes; the <svg> wrapper (size, stroke, color,
// accessibility) comes from createIcon, so every icon behaves the same.
// A small home-made alternative to SVGR: our icons are simple, hand-drawn
// stroke shapes, so a few lines of string handling is all that's needed.
//
// Run with: pnpm --filter @jo-ui/ui-icons generate

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";

const SVG_DIR = "svg";
const OUT_DIR = "src/icons";
const HEADER = "// Generated by scripts/generate.js from svg/. Do not edit; edit the SVG and re-run.\n";

/** "chevron-down" → "ChevronDown" */
const pascalCase = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

/** SVG attribute names are kebab-case; React wants camelCase (stroke-width → strokeWidth). */
const toJsx = (markup) => markup.replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (_, attr) => ` ${attr.replace(/-([a-z])/g, (__, c) => c.toUpperCase())}=`);

const files = (await readdir(SVG_DIR)).filter((file) => file.endsWith(".svg")).sort();

// Start clean so a deleted SVG doesn't leave a stale component behind.
await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const exports = [];
for (const file of files) {
  const source = await readFile(`${SVG_DIR}/${file}`, "utf8");
  const inner = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(source)?.[1]?.trim();
  if (!inner) throw new Error(`${file}: no <svg>…</svg> content found`);

  const name = `${pascalCase(file.replace(/\.svg$/, ""))}Icon`;
  const shapes = toJsx(inner)
    .split("\n")
    .map((line) => `    ${line.trim()}`)
    .join("\n");

  await writeFile(
    `${OUT_DIR}/${name}.tsx`,
    `${HEADER}import { createIcon } from "../createIcon";

export const ${name} = createIcon(
  "${name}",
  <>
${shapes}
  </>,
);
`,
  );
  exports.push(`export { ${name} } from "./icons/${name}";`);
}

await writeFile(
  "src/index.ts",
  `${HEADER}export { createIcon } from "./createIcon";
export type { IconProps } from "./createIcon";

${exports.join("\n")}
`,
);

console.log(`✔︎ Generated ${files.length} icons into ${OUT_DIR}/`);
